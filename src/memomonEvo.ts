function line(
  key: string, emoji: string, color: string,
  names: [string, string, string], descs: [string, string, string],
  flavor: string, fav: string[], dis: string[], chat: string[], tip: string[],
): EvoLine {
  const ids = [1, 2, 3].map(n => `${key}${n}`);
  const stages = names.map((name, i) => ({
    id: ids[i], name, stage: (i + 1) as EvoStage, desc: descs[i], evolvesTo: ids[i + 1], sprite: `ev_${key}${i + 1}`,
  })) as [EvoMon, EvoMon, EvoMon];
  return { key, emoji, color, flavor, fav, dis, chat, tip, stages };
}


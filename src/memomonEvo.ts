const ids = (key: string) => [1, 2, 3].map(n => `${key}${n}`);

// 段階ごとに固有の性格・セリフを持つ系統
type StageSpec = {
  name: string;
  desc: string;
  chat: string[];
  tip: string[];
  reactions: EvoReactions;
  gift?: EvoGift;
};
function individual(
  key: string, emoji: string, color: string,
  flavor: string, fav: string[], dis: string[],
  specs: [StageSpec, StageSpec, StageSpec],
): EvoLine {
  const id = ids(key);
  const stages = specs.map((s, i) => ({
    ...s,
    id: id[i],
    stage: (i + 1) as EvoStage,
    evolvesTo: id[i + 1],
    sprite: `ev_${key}${i + 1}`,
  })) as [EvoMon, EvoMon, EvoMon];
  return { key, emoji, color, flavor, fav, dis, stages };
}

// まだ個別化していない系統。系統の 1 組を 3 段階に配る（従来どおりの挙動）
function shared(
  key: string, emoji: string, color: string,
  names: [string, string, string], descs: [string, string, string],
  flavor: string, fav: string[], dis: string[], chat: string[], tip: string[],
): EvoLine {
  const id = ids(key);
  const stages = names.map((name, i) => ({
    id: id[i], name, stage: (i + 1) as EvoStage, desc: descs[i],
    evolvesTo: id[i + 1], sprite: `ev_${key}${i + 1}`,
    chat, tip, reactions: EVO_REACTIONS,
  })) as [EvoMon, EvoMon, EvoMon];
  return { key, emoji, color, flavor, fav, dis, stages };
}


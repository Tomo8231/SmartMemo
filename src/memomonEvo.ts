export type EvoStage = 1 | 2 | 3;
export type EvoMon = { id: string; name: string; stage: EvoStage; desc: string; evolvesTo?: string; sprite: string };
export type EvoLine = {
  key: string;
  emoji: string;
  color: string;
  flavor: string;
  fav: string[];
  dis: string[];
  chat: string[];
  tip: string[];
  stages: [EvoMon, EvoMon, EvoMon];
};


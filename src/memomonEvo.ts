// 3 段階で進化するメモモンの系統データ。
// 画像は public/sprites/ev_<key><段階>_<状態>_<コマ>.png（144x156）。
// 1 段階目だけガチャに出て、なつき度 MAX の子を にわに出したままタスクを完了すると進化する。
//
// 性格・セリフは「個体ごと」に持つ。以前は系統で 1 組を 3 段階が共有していたため、
// 3 段階目でも 1 段階目と同じことを話し、なでた／食べたときの反応に至っては
// 全 102 体が同じだった。いまは 102 体すべてが独立した性格とセリフを持つ。
//
// 系統（key/emoji/color/flavor/fav/dis）は、スプライトの割り当てと
// ガチャの排出単位として残している。進化の道筋もこれで決まる。

export type EvoStage = 1 | 2 | 3;

export type EvoReactions = {
  pet: string[];
  feedFav: string[];
  feedNormal: string[];
  feedDis: string[];
};

// なつき度 MAX で手に入る、その姿だけのおくりもの。
// 進化系は画像を持たないので emoji で見せる。
export type EvoGift = { emoji: string; name: string; comment: string };

export type EvoMon = {
  id: string;
  name: string;
  stage: EvoStage;
  desc: string;
  evolvesTo?: string;
  sprite: string;
  chat: string[];
  tip: string[];
  reactions: EvoReactions;
  gift: EvoGift;
};

export type EvoLine = {
  key: string;
  emoji: string;
  color: string;
  flavor: string;
  fav: string[];
  dis: string[];
  stages: [EvoMon, EvoMon, EvoMon];
};

// 進化に必要な「なつき度 MAX で、にわに出したまま完了したタスク」の数（段階ごと）
export const EVO_TASKS_TO_EVOLVE: Record<1 | 2, number> = { 1: 20, 2: 50 };

export const EVO_TIP = 'なつき度MAXで、にわに出したままタスクを完了すると進化に近づくよ';

type StageSpec = {
  name: string;
  desc: string;
  chat: string[];
  tip: string[];
  reactions: EvoReactions;
  gift: EvoGift;
};

function line(
  key: string, emoji: string, color: string,
  flavor: string, fav: string[], dis: string[],
  specs: [StageSpec, StageSpec, StageSpec],
): EvoLine {
  const ids = [1, 2, 3].map(n => `${key}${n}`);
  const stages = specs.map((sp, i) => ({
    ...sp,
    id: ids[i],
    stage: (i + 1) as EvoStage,
    evolvesTo: ids[i + 1],
    sprite: `ev_${key}${i + 1}`,
  })) as [EvoMon, EvoMon, EvoMon];
  return { key, emoji, color, flavor, fav, dis, stages };
}


//
// セリフは「段階ごと」に持つ。以前は系統で 1 組を 3 段階が共有していたため、
// 3 段階目でも 1 段階目と同じことを話し、なでた／食べたときの反応に至っては
// 全 102 体が同じだった。individual() で書いた系統は段階ごとに固有の性格を持つ。
// まだ個別化していない系統は shared() で、系統の 1 組を 3 段階に配って回している
// （挙動は従来と同じ。資料が揃いしだい individual() へ移す）。

export type EvoStage = 1 | 2 | 3;

export type EvoReactions = {
  pet: string[];
  feedFav: string[];
  feedNormal: string[];
  feedDis: string[];
};

// なつき度 MAX で手に入る、その姿だけのおくりもの。
// 進化系は画像を持たないので emoji で見せる。
export type EvoGift = { emoji: string; name: string; comment: string };

export type EvoMon = {
  id: string;
  name: string;
  stage: EvoStage;
  desc: string;
  evolvesTo?: string;
  sprite: string;
  chat: string[];
  tip: string[];
  reactions: EvoReactions;
  gift?: EvoGift;
};

export type EvoLine = {
  key: string;
  emoji: string;
  color: string;
  flavor: string;
  fav: string[];
  dis: string[];
  stages: [EvoMon, EvoMon, EvoMon];
};

